// Turns the PLAID design system's tokens.json into CSS custom properties
// (F007 PR A). Run by `pnpm generate`; scripts/check-codegen.sh diffs the
// output. Usage: node scripts/build-tokens.mjs [out.css]
import { readFileSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const here = dirname(fileURLToPath(import.meta.url))
const tokens = JSON.parse(readFileSync(join(here, '../src/design/tokens.json'), 'utf8'))
const out = process.argv[2] ?? join(here, '../src/design/tokens.css')

// "{neutral-155}" refers to another token.
const ref = (v) => String(v).replace(/\{([a-z0-9-]+)\}/g, 'var(--$1)')

const dark = []
const light = []
const add = (name, value) => {
  if (value && typeof value === 'object') {
    dark.push(`  --${name}: ${ref(value.dark)};`)
    if (value.light !== undefined) light.push(`  --${name}: ${ref(value.light)};`)
  } else {
    dark.push(`  --${name}: ${ref(value)};`)
  }
}

for (const t of tokens.color.tokens) add(t.name, t.value)
for (const group of ['spacing', 'radius', 'shadow', 'duration', 'easing', 'scale', 'opacity']) {
  for (const t of tokens[group].tokens) add(t.name, t.value)
}
add('font-text', tokens.type.families.text)
add('font-display', tokens.type.families.display)
// The design system's code font: system mono, no webfont.
add('font-code', 'ui-monospace, "SF Mono", Menlo, Consolas, monospace')

const styles = tokens.type.groups
  .flatMap((g) => g.styles)
  .map((s) => {
    const family = s.family === 'display' ? 'var(--font-display)' : 'var(--font-text)'
    const spacing = s.letterSpacing ? `\n  letter-spacing: ${s.letterSpacing};` : ''
    return `.type-${s.name} {\n  font: ${s.fontWeight} ${s.fontSize}/${s.lineHeight} ${family};${spacing}\n}`
  })

const css = `/* Generated by scripts/build-tokens.mjs from tokens.json (${tokens.name} v${tokens.version}). Don't edit. */
:root {
  color-scheme: dark;
${dark.join('\n')}
}

:root[data-theme='light'] {
  color-scheme: light;
${light.join('\n')}
}

@media (prefers-color-scheme: light) {
  :root:not([data-theme]) {
    color-scheme: light;
${light.map((l) => '  ' + l).join('\n')}
  }
}

${styles.join('\n\n')}
`
writeFileSync(out, css)
